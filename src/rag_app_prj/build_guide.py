def build() -> Path:
    if not FONT.is_file():
        raise FileNotFoundError(f"한글 글꼴이 없습니다: {FONT}")

    OUT.parent.mkdir(parents=True, exist_ok=True)

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=False)
    pdf.add_font("Malgun", "", str(FONT))

    for title, paragraphs in PAGES:
        pdf.add_page()
        pdf.set_fill_color(14, 77, 108)
        pdf.rect(0, 0, 210, 28, "F")
        pdf.set_fill_color(224, 122, 61)
        pdf.rect(0, 28, 210, 2.2, "F")

        pdf.set_text_color(246, 243, 238)
        pdf.set_font("Malgun", size=10)
        pdf.set_xy(16, 7)
        pdf.cell(0, 6, "부산 2박 3일 여행 가이드")
        pdf.set_font("Malgun", size=16)
        pdf.set_xy(16, 15)
        pdf.cell(0, 8, title)

        pdf.set_text_color(28, 42, 51)
        pdf.set_font("Malgun", size=11)
        y = 40
        for paragraph in paragraphs:
            pdf.set_xy(16, y)
            pdf.multi_cell(178, 7, paragraph)
            y = pdf.get_y() + 4
            if y > 268:
                raise RuntimeError(f"페이지를 넘었습니다: {title}")

        pdf.set_text_color(31, 138, 112)
        pdf.set_font("Malgun", size=9)
        pdf.set_xy(16, 282)
        pdf.cell(0, 6, f"{pdf.page_no()}  /  {len(PAGES)}")

    pdf.output(str(OUT))
    return OUT


if __name__ == "__main__":
    path = build()
    print(path)
